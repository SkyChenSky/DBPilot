-- smoke-blocking.sql : 阻塞分析页测试负载（MySQL）
-- 结构：前置 smoke-base.sql（smoke_block 表）→ ① 窗口脚本（每个窗口在独立 mysql 客户端 /
--        Navicat 会话中执行该段；同一文件整跑会串行执行——自己等自己的锁立即获授、
--        产生不了阻塞）→ ② 验证说明 → ③ 清理
-- 前置：performance_schema=ON（含 data_locks 表可读）
--
-- 制造一条 2 层阻塞链（睡着拿锁头 + 受害者）：
--   窗口 1 持 id=1 行 X 锁后空闲（事务开着，Command=Sleep）
--   窗口 2 等同一行 X 锁挂起

-- ---------------------------------------------------------------------------
-- ① 窗口脚本（每段在独立会话执行；按窗口编号依次起跑）
-- ---------------------------------------------------------------------------

-- 窗口 1（睡着拿锁头）：执行后保持空闲（不 COMMIT / 不关连接），持锁 1~2 分钟
USE dbpilot_smoke;
BEGIN;
SELECT * FROM smoke_block WHERE id = 1 FOR UPDATE;
-- 此后会话 Command=Sleep 但事务持锁（"睡着拿锁"最经典场景）

-- 窗口 2（受害者）：窗口 1 执行完 SELECT 后立即执行（将挂起等待行锁）
USE dbpilot_smoke;
UPDATE smoke_block SET v = v + 1 WHERE id = 1;

-- 解除：窗口 1 执行 COMMIT;（或 ROLLBACK;）→ 受害者立刻放行

-- ---------------------------------------------------------------------------
-- ② 验证：窗口全部等待期间打开 DBPilot 阻塞分析页（5s 轮询）
--    总览：1 条链、最长等待增长至约 1~2 分钟、涉及 2 个会话
--    树  ：头（SLEEPING（持有事务锁），openTranCount=1，事务持有时长持续增长）
--          → 受害者（suspended，Waiting for row lock，等待秒数增长）
--    锁  ：头 GRANT（TABLE IX + RECORD X\REC_NOT_GAP），受害者同记录 WAIT
--    完整批文本 / 睡着头最后语句：依赖 RDS 参数组 events_statements_history_size>0 +
--          performance_schema_max_sql_text_length=1024（置 0 时头 SQL 为空是参数边界，非 bug）
--    历史 tab：等待超过阈值（实例配置阻塞阈值，默认 10s）后留痕开/续，
--          COMMIT 后自动解除（头会话/数据库列齐全）
-- ---------------------------------------------------------------------------

